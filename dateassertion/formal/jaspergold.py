import os
import re
import subprocess
import time
from typing import Any

from dateassertion.ir.schema import FormalRunResult, PropertyIR, dump_json
from .result_parser import parse_jasper_results
from .runner import FormalRunner


def execution_timeout(config: dict[str, Any]) -> int | None:
    """Zero/None means no wrapper deadline, not an immediate subprocess kill."""
    value = config.get("timeout_seconds", 900)
    if value is None:
        return None
    value = int(value)
    if value < 0:
        raise ValueError("timeout_seconds must be nonnegative or None")
    return value or None


def _log_text(value: str | bytes | None) -> str:
    return value.decode("utf-8", errors="replace") if isinstance(value, bytes) else value or ""


def generate_tcl(
    rtl_files: list[str],
    property_file: str,
    top_module: str,
    output_dir: str | Path,
    config: dict[str, Any],
    property_ids: list[str] | None = None,
) -> Path:
    output = Path(output_dir).resolve()
    output.mkdir(parents=True, exist_ok=True)
    proof_scope = str(config.get("proof_scope", "all")).lower()
    if proof_scope not in {"all", "asserts"}:
        raise ValueError("proof_scope must be 'all' or 'asserts'")
    coverage_types = "{proof stimuli}" if config.get("measure_stimuli", False) else "proof"
    lines = [
        "# Generated by microarchitecture assertion pipeline.",
        "clear -all",
        "set_elaborate_single_run_mode off",
        f"check_cov -init -model {{branch statement expression toggle functional}} -type {coverage_types} -enable_prove_based_proof_core -proof_core_include_failing -toggle_ports_only -exclude_bind_hierarchies",
    ]
    include_args = " ".join(
        f"-incdir {{{Path(item).resolve()}}}" for item in config.get("include_dirs", [])
    )
    for rtl in rtl_files:
        command = "analyze -sv"
        if include_args:
            command += f" {include_args}"
        lines.append(f"{command} {{{Path(rtl).resolve()}}}")
    status_list = (
        "covered uncovered unreachable deadcode unprocessed checked unchecked undetectable"
        if config.get("measure_stimuli", False)
        else "checked unchecked undetectable"
    )
    lines.extend(
        [
            f"analyze -sv {{{Path(property_file).resolve()}}}",
            f"elaborate -top {top_module}",
            f"clock {config.get('clock', 'clk')}",
        ]
    )
    reset = config.get("reset", "resetn")
    reset_expr = f"!{reset}" if config.get("reset_active_low", True) else reset
    if config.get("prove_orchestration") is False:
        lines.append("set_prove_orchestration off")
    elif config.get("prove_orchestration") is True:
        lines.append("set_prove_orchestration on")
    if int(config.get("proofgrid_max_local_jobs", 0)) > 0:
        lines.append(f"set_proofgrid_max_local_jobs {int(config['proofgrid_max_local_jobs'])}")
    if config.get("engine_mode"):
        lines.append(f"set_engine_mode {{{config['engine_mode']}}}")
    lines.append(f"reset -expression {{{reset_expr}}}")
    if proof_scope == "asserts":
        # Keep assertion proof from being starved by automatically generated
        # precondition covers.  The same-session cover pass leaves its statuses
        # in formal_report.txt for conservative target-level vacuity parsing.
        lines.extend([
            f"prove -all -asserts -time_limit {config.get('prove_time_limit', '300s')}",
            f"prove -all -covers -time_limit {config.get('precondition_probe_time_limit', '60s')}",
        ])
    else:
        lines.append(f"prove -all -time_limit {config.get('prove_time_limit', '300s')}")
    if str(config.get("coverage_time_limit", "")) == "0s":
        # Coverage must not inherit the preceding assertion/cover time limit.
        lines.append("set_prove_time_limit 0s")
    if config.get("measure_stimuli", False):
        stimuli = "check_cov -measure -type stimuli"
        if config.get("coverage_time_limit"):
            stimuli += f" -time_limit {config['coverage_time_limit']}"
        if config.get("coverage_engine_mode"):
            stimuli += f" -stimuli_engine_mode {{{config['coverage_engine_mode']}}}"
        lines.append(stimuli)
    proof_measure = "check_cov -measure -type proof"
    if config.get("coverage_time_limit"):
        proof_measure += f" -time_limit {config['coverage_time_limit']}"
    if config.get("measure_proof_coverage", True):
        lines.append(proof_measure)
    lines.extend(
        [
            "report -force -result -file {formal_report.txt}",
            "check_cov -report -type formal -report_file {coverage_report.txt} -force",
            "redirect -file {coverage_items.tsv} -force {",
            "    foreach status {covered_and_checked uncovered_or_unchecked unreachable_or_undetectable} {",
            "        foreach item [check_cov -list -status $status -silent] {",
            "            puts \"$status\\t$item\"",
            "        }",
            "    }",
            "}",
            "redirect -file {coverage_statuses.tsv} -force {",
            f"    foreach status {{{status_list}}} {{",
            "        foreach item [check_cov -list -status $status -silent] {",
            "            puts \"$status\\t$item\"",
            "        }",
            "    }",
            "}",
            "set proof_targets [check_cov -get_assert_id]",
            "redirect -file {proof_core_report.txt} -force {check_cov -get_target_info $proof_targets -name -prove_status -proof_core}",
        ]
    )
    if config.get("property_attribution") and property_ids:
        attribution_time_limit = str(config.get("attribution_time_limit", "30s"))
        lines.extend([
            "set attribution_target_fp [open {target_results.tsv} w]",
            "foreach target [check_cov -get_assert_id] {",
            "    puts $attribution_target_fp \"$target\\t[check_cov -get_target_info $target -name -prove_status -coi -proof_core -silent]\"",
            "}",
            "close $attribution_target_fp",
            "set attribution_attr_fp [open {property_proof_core_items.tsv} w]",
        ])
        for property_id in property_ids:
            label = "p_" + re.sub(r"[^A-Za-z0-9_$]", "_", property_id)
            pattern = rf".*{re.escape(label)}$"
            info_pattern = rf".*{re.escape(label)}"
            lines.extend([
                f"puts $attribution_attr_fp {{PROPERTY_BEGIN\t{property_id}}}",
                "set attribution_matched_targets 0",
                "set attribution_pending_targets 0",
                "foreach target [check_cov -get_assert_id] {",
                "    set attribution_target_name [check_cov -get_target_info $target -name -silent]",
                f"    if {{[regexp {{{info_pattern}}} $attribution_target_name]}} {{",
                "        incr attribution_matched_targets",
                "        set attribution_target_status [check_cov -get_target_info $target -prove_status -silent]",
                "        if {[string match -nocase {*Unprocessed*} $attribution_target_status] || [string match -nocase {*Undetermined*} $attribution_target_status] || [string match -nocase {*Unknown*} $attribution_target_status] || [string match -nocase {*Error*} $attribution_target_status]} {",
                "            incr attribution_pending_targets",
                "        }",
                "    }",
                "}",
                "if {$attribution_matched_targets > 0 && $attribution_pending_targets == 0} {",
                f"    puts $attribution_attr_fp {{ATTRIBUTION_STATUS\t{property_id}\tMEASURED}}",
                "    check_cov -measure -clear",
                f"    check_cov -measure -type proof -time_limit {attribution_time_limit} -property {{{pattern}}} -regexp",
                "    foreach item [check_cov -list -status checked -silent] {",
                f"        puts $attribution_attr_fp \"{property_id}\\tchecked\\t$item\"",
                "    }",
                "} else {",
                f"    puts $attribution_attr_fp \"ATTRIBUTION_STATUS\\t{property_id}\\tSKIPPED_PENDING_TARGETS\\tmatched=$attribution_matched_targets,pending=$attribution_pending_targets\"",
                "}",
                f"puts $attribution_attr_fp {{PROPERTY_END\t{property_id}}}",
            ])
        lines.extend([
            "close $attribution_attr_fp",
        ])
    lines.extend(["exit", ""])
    script = output / "run_jaspergold.tcl"
    script.write_text("\n".join(lines), encoding="utf-8")
    return script


def generate_reachability_tcl(
    rtl_files: list[str],
    top_module: str,
    output_dir: str | Path,
    config: dict[str, Any],
) -> Path:
    """Create a stimuli-only run so reachability cannot perturb proof-core coverage."""
    output = Path(output_dir).resolve()
    output.mkdir(parents=True, exist_ok=True)
    lines = [
        "# Independent DUT-only reachability run for effective denominator evidence.",
        "clear -all",
        "set_elaborate_single_run_mode off",
        "check_cov -init -model {branch statement expression toggle functional} -type stimuli -toggle_ports_only",
    ]
    include_args = " ".join(
        f"-incdir {{{Path(item).resolve()}}}" for item in config.get("include_dirs", [])
    )
    for rtl in rtl_files:
        command = "analyze -sv"
        if include_args:
            command += f" {include_args}"
        lines.append(f"{command} {{{Path(rtl).resolve()}}}")
    lines.extend([f"elaborate -top {top_module}", f"clock {config.get('clock', 'clk')}"])
    reset = config.get("reset", "resetn")
    reset_expr = f"!{reset}" if config.get("reset_active_low", True) else reset
    if config.get("prove_orchestration") is False:
        lines.append("set_prove_orchestration off")
    elif config.get("prove_orchestration") is True:
        lines.append("set_prove_orchestration on")
    if int(config.get("proofgrid_max_local_jobs", 0)) > 0:
        lines.append(f"set_proofgrid_max_local_jobs {int(config['proofgrid_max_local_jobs'])}")
    if config.get("coverage_engine_mode"):
        lines.append(f"set_engine_mode {{{config['coverage_engine_mode']}}}")
    measure = "check_cov -measure -type stimuli"
    if config.get("coverage_time_limit"):
        measure += f" -time_limit {config['coverage_time_limit']}"
    if config.get("coverage_engine_mode"):
        measure += f" -stimuli_engine_mode {{{config['coverage_engine_mode']}}}"
    lines.extend(
        [
            f"reset -expression {{{reset_expr}}}",
            measure,
            "check_cov -report -type stimuli -report_file {reachability_report.txt} -force",
            "redirect -file {coverage_statuses.tsv} -force {",
            "    foreach status {covered uncovered unreachable deadcode unprocessed} {",
            "        foreach item [check_cov -list -status $status -silent] {",
            "            puts \"$status\\t$item\"",
            "        }",
            "    }",
            "}",
            "exit",
            "",
        ]
    )
    script = output / "run_reachability.tcl"
    script.write_text("\n".join(lines), encoding="utf-8")
    return script


def run_coverage_reachability(
    rtl_files: list[str],
    top_module: str,
    output_dir: str | Path,
    config: dict[str, Any],
) -> dict[str, Any]:
    """Run the independent stimuli proof and return auditable execution metadata."""
    output = Path(output_dir).resolve()
    script = generate_reachability_tcl(rtl_files, top_module, output, config)
    executable = Path(config["executable"]).resolve()
    project = output / f"jgproject_{int(time.time())}"
    command = [str(executable), "-allow_unsupported_OS", "-batch", "-proj", str(project), str(script)]
    env = os.environ.copy()
    if config.get("license_file"):
        env[config.get("license_env", "CDS_LIC_FILE")] = str(config["license_file"])
    start = time.monotonic()
    try:
        completed = subprocess.run(
            command,
            cwd=output,
            env=env,
            text=True,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            timeout=execution_timeout(config),
            check=False,
        )
        stdout = completed.stdout
        stderr = completed.stderr
        return_code = completed.returncode
    except subprocess.TimeoutExpired as exc:
        stdout = exc.stdout or ""
        stderr = exc.stderr or ""
        if isinstance(stdout, bytes):
            stdout = stdout.decode("utf-8", errors="replace")
        if isinstance(stderr, bytes):
            stderr = stderr.decode("utf-8", errors="replace")
        stderr += "\nJasperGold reachability execution timed out"
        return_code = -1
    (output / "jaspergold.stdout.log").write_text(stdout, encoding="utf-8", errors="replace")
    (output / "jaspergold.stderr.log").write_text(stderr, encoding="utf-8", errors="replace")
    status_file = output / "coverage_statuses.tsv"
    metadata = {
        "tool": "JasperGold 21.12",
        "runtime_seconds": round(time.monotonic() - start, 3),
        "return_code": return_code,
        "project": str(project),
        "status_file": str(status_file),
        "report": str(output / "reachability_report.txt"),
        "source_digest": hashlib.sha256(b"".join(Path(file).read_bytes() for file in rtl_files)).hexdigest(),
    }
    dump_json(output / "reachability_run.json", metadata)
    if return_code != 0 or not status_file.is_file():
        raise RuntimeError(f"independent JasperGold reachability run failed; see {output}")
    return metadata


class JasperGoldRunner(FormalRunner):
    def run(
        self,
        rtl_files: list[str],
        property_file: str,
        top_module: str,
        properties: list[PropertyIR],
        output_dir: str | Path,
        config: dict[str, Any],
    ) -> FormalRunResult:
        output = Path(output_dir).resolve()
        output.mkdir(parents=True, exist_ok=True)
        script = generate_tcl(
            rtl_files, property_file, top_module, output, config,
            property_ids=[item.property_id for item in properties],
        )
        executable = Path(config["executable"]).resolve()
        log_path = output / "jaspergold.stdout.log"
        error_path = output / "jaspergold.stderr.log"
        project = output / f"jgproject_{int(time.time())}"
        command = [str(executable), "-allow_unsupported_OS", "-batch", "-proj", str(project), str(script)]
        env = os.environ.copy()
        license_env = config.get("license_env", "CDS_LIC_FILE")
        if config.get("license_file"):
            env[license_env] = str(config["license_file"])
        start = time.monotonic()
        notes: list[str] = []
        return_code = None
        try:
            completed = subprocess.run(
                command,
                cwd=output,
                env=env,
                text=True,
                stdout=subprocess.PIPE,
                stderr=subprocess.PIPE,
                timeout=execution_timeout(config),
                check=False,
            )
            return_code = completed.returncode
            log_path.write_text(completed.stdout, encoding="utf-8", errors="replace")
            error_path.write_text(completed.stderr, encoding="utf-8", errors="replace")
        except subprocess.TimeoutExpired as exc:
            log_path.write_text(_log_text(exc.stdout), encoding="utf-8", errors="replace")
            error_path.write_text(_log_text(exc.stderr), encoding="utf-8", errors="replace")
            notes.append("JasperGold execution timed out")
        except OSError as exc:
            error_path.write_text(str(exc), encoding="utf-8")
            notes.append(f"JasperGold launch failed: {exc}")
        runtime = time.monotonic() - start

        parsed, summary, coverage = parse_jasper_results(
            properties,
            output / "formal_report.txt",
            output / "proof_core_report.txt",
            output / "coverage_report.txt",
            log_path,
        )
        for item in parsed:
            if item.result == "FAIL":
                item.counterexample_path = str(project)
                item.notes = "CEX is retained in the JasperGold project database; no standalone waveform was exported."
        if return_code not in (None, 0):
            notes.append(f"JasperGold exited with code {return_code}")
        if summary["total"] and summary["not_evaluated"] == summary["total"]:
            status = "ERROR" if notes or return_code not in (None, 0) else "NOT_EVALUATED"
        elif summary["failed"]:
            status = "FAIL"
        elif summary["proven"] == summary["total"] and summary["total"]:
            status = "PASS"
        elif summary["accepted_correct"] == summary["total"] and summary["total"]:
            status = "TIMEOUT_ACCEPTED"
        else:
            status = "NOT_EVALUATED"
        result = FormalRunResult(
            status=status,
            tool="JasperGold 21.12",
            runtime_seconds=round(runtime, 3),
            log_path=str(log_path),
            results=parsed,
            summary=summary,
            coverage=coverage,
            notes=notes,
        )
        dump_json(output / "formal_results.json", result)
        return result
